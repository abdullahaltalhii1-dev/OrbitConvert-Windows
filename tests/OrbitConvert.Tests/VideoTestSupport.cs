using System.Globalization;
using OrbitConvert.App.Services.Media;
using OrbitConvert.App.Services.Video;

namespace OrbitConvert.Tests;

/// <summary>
/// Real FFmpeg tests use the pinned development build (tools/Get-FFmpeg.ps1). They are skipped with a reason when it
/// is missing, unless ORBITCONVERT_REQUIRE_FFMPEG=1 (set in CI), in which case they run and fail loudly.
/// </summary>
internal static class FfmpegTestTools
{
    private static readonly Lazy<string?> Directory_ = new(Find);

    public static string? Directory => Directory_.Value;

    public static bool Required => Environment.GetEnvironmentVariable("ORBITCONVERT_REQUIRE_FFMPEG") == "1";

    public static string SkipReason => Directory is null && !Required
        ? "Real FFmpeg tests need the pinned build: run tools/Get-FFmpeg.ps1 or set ORBITCONVERT_FFMPEG_DIR." : null!;

    public static string Ffmpeg => Path.Combine(Directory ?? throw new InvalidOperationException("FFmpeg test build not found."), "ffmpeg.exe");

    public static string Ffprobe => Path.Combine(Directory ?? throw new InvalidOperationException("FFmpeg test build not found."), "ffprobe.exe");

    public static VideoConversionService Service(H264Encoder? encoder = null, IProcessRunner? runner = null) =>
        new(Locator(), runner ?? new ProcessRunner(), encoder);

    public static FfmpegLocator Locator() =>
        new(Path.Combine(Path.GetTempPath(), "OrbitConvert.Tests", "no-bundle"), name => name == FfmpegLocator.OverrideVariable ? Directory : null);

    private static string? Find()
    {
        var candidates = new[]
        {
            Environment.GetEnvironmentVariable(FfmpegLocator.OverrideVariable),
            Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData),
                "OrbitConvert", "dev-tools", "ffmpeg-9.0.2", "ffmpeg-9.0.2-essentials_build", "bin"),
        };
        return candidates.FirstOrDefault(directory => !string.IsNullOrWhiteSpace(directory) &&
            File.Exists(Path.Combine(directory, "ffmpeg.exe")) && File.Exists(Path.Combine(directory, "ffprobe.exe")));
    }
}

[AttributeUsage(AttributeTargets.Method)]
internal sealed class FfmpegFactAttribute : FactAttribute
{
    public FfmpegFactAttribute() => Skip = FfmpegTestTools.SkipReason;
}

[AttributeUsage(AttributeTargets.Method)]
internal sealed class FfmpegTheoryAttribute : TheoryAttribute
{
    public FfmpegTheoryAttribute() => Skip = FfmpegTestTools.SkipReason;
}

/// <summary>Deterministic synthetic videos generated by the pinned FFmpeg build (lavfi test sources).</summary>
internal static class VideoFixtures
{
    private static readonly string Root = Path.Combine(Path.GetTempPath(), "OrbitConvert.Tests", "video-fixtures-" + Environment.ProcessId);
    private static readonly Dictionary<string, string> Cache = [];
    private static readonly object Gate = new();

    /// <summary>Generates (once per test run) a fixture from FFmpeg arguments placed between the inputs and the output.</summary>
    public static string Get(string name, string inputs, string encode)
    {
        lock (Gate)
        {
            if (Cache.TryGetValue(name, out var cached)) { return cached; }
            Directory.CreateDirectory(Root);
            var path = Path.Combine(Root, name);
            var arguments = new List<string> { "-hide_banner", "-v", "error", "-nostdin", "-y" };
            arguments.AddRange(Split(inputs));
            arguments.AddRange(Split(encode));
            arguments.Add(path);
            Run(FfmpegTestTools.Ffmpeg, arguments);
            Cache[name] = path;
            return path;
        }
    }

    public static string Standard(int seconds = 3, string size = "320x240") =>
        Get($"h264-aac-{seconds}s-{size}.mp4", $"-f lavfi -i testsrc2=size={size}:rate=25:duration={seconds} -f lavfi -i sine=frequency=440:duration={seconds}",
            "-c:v libx264 -preset ultrafast -pix_fmt yuv420p -c:a aac -b:a 96k -shortest");

    /// <summary>Runs a tool through the app's own runner, so a stalled process start fails the test instead of hanging it.</summary>
    public static string Run(string executable, IEnumerable<string> arguments)
    {
        var result = Execute(executable, arguments);
        if (!result.Succeeded)
        {
            throw new InvalidOperationException($"{Path.GetFileName(executable)} {result.Outcome} (exit {result.ExitCode}): {result.StandardError}");
        }
        return result.StandardOutput;
    }

    /// <summary>Structural similarity of <paramref name="candidate"/> against <paramref name="reference"/> (1 = identical).</summary>
    public static double Ssim(string candidate, string reference)
    {
        var result = Execute(FfmpegTestTools.Ffmpeg, ["-hide_banner", "-nostdin", "-i", candidate, "-i", reference, "-lavfi", "[0:v][1:v]ssim", "-f", "null", "-"]);
        var log = result.StandardError;
        var marker = log.LastIndexOf(" All:", StringComparison.Ordinal);
        Assert.True(result.Succeeded && marker >= 0, $"SSIM was not reported ({result.Outcome}): " + log);
        var text = new string(log[(marker + 5)..].TakeWhile(c => char.IsDigit(c) || c == '.').ToArray());
        return double.Parse(text, CultureInfo.InvariantCulture);
    }

    private static ProcessRunResult Execute(string executable, IEnumerable<string> arguments) =>
        new ProcessRunner().RunAsync(new ProcessRunRequest(executable, arguments.ToList(), TimeSpan.FromMinutes(3)), CancellationToken.None)
            .ConfigureAwait(false).GetAwaiter().GetResult();

    private static IEnumerable<string> Split(string arguments) => arguments.Split(' ', StringSplitOptions.RemoveEmptyEntries);
}
